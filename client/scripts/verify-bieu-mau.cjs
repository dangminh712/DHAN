// Run against the local Vite app. Set PLAYWRIGHT_MODULE_PATH if Playwright is supplied by a shared runtime.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
(async () => {
  const browser = await chromium.launch({ headless: true, channel: process.env.BROWSER_CHANNEL || 'msedge' });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await context.addInitScript(() => { window.print = () => { window.__printed = true; }; });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  try {
    await page.goto((process.env.FORMS_TEST_URL || 'http://localhost:5173') + '/#/bieu-mau');
    const open = () => page.getByRole('button', { name: 'Viết máy (Điền online)', exact: true }).nth(1).click();
    await open();
    const paper = page.locator('#bieumau-print-area');
    await paper.locator('table').waitFor();
    const originalRows = await paper.locator('tr').count();
    await paper.locator('[data-bm-action="add-row"]').click();
    assert.equal(await paper.locator('tr').count(), originalRows + 1);
    const lastField = paper.locator('tr').last().locator('[contenteditable]').first();
    await lastField.fill('Dòng mới đã lưu');
    await lastField.press('Enter');
    await lastField.pressSequentially('Nội dung dòng hai');
    assert.match(await lastField.innerText(), /Dòng mới đã lưu\nNội dung dòng hai/);
    assert.equal(await paper.locator('td[contenteditable]').first().evaluate(e => getComputedStyle(e).display), 'table-cell');
    assert.equal(await page.locator('#root').evaluate(e => e.inert), true);
    await page.locator('.bm-toolbar-actions button').first().focus();
    await page.keyboard.press('Shift+Tab');
    assert.equal(await page.evaluate(() => !!document.activeElement.closest('.bm-modal-host')), true);
    assert.ok(page.url().endsWith('#/bieu-mau'));
    await page.getByTitle('Đóng cửa sổ soạn thảo (Esc)').click();
    await open();
    await paper.locator('table').waitFor();
    assert.equal(await paper.locator('tr').count(), originalRows + 1);
    assert.match(await paper.locator('tr').last().innerText(), /Nội dung dòng hai/);
    await paper.locator('[data-bm-action="delete-row"]').click();
    assert.equal(await paper.locator('tr').count(), originalRows);
    await page.getByRole('button', { name: 'In (Ctrl+P)', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('[data-bm-print-frame]')?.contentWindow.__printed);
    const printHtml = await page.locator('[data-bm-print-frame]').evaluate(e => e.contentDocument.documentElement.outerHTML);
    assert.match(printHtml, /THỐNG KÊ TÀI LIỆU/i);
    assert.doesNotMatch(printHtml, /216 biểu mẫu|Mở tệp ngoài|nav-container/);
    await page.emulateMedia({ media: 'print' });
    assert.equal(await page.locator('#root').isVisible(), false);
    await page.emulateMedia({ media: 'screen' });
    await page.locator('[data-bm-print-frame]').evaluate(e => e.remove());
    console.log('PASS legacy: rows, multiline, table layout, immediate draft restore, focus isolation, isolated print');
    for (let i = 0; i < 40; i++) {
      await paper.locator('[data-bm-action="add-row"]').click();
      await paper.locator('tr').last().locator('[contenteditable]').first().fill(`Tài liệu kiểm tra số ${i + 1}`);
    }
    await page.getByRole('button', { name: 'In (Ctrl+P)', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('[data-bm-print-frame]')?.contentWindow.__printed);
    const longHtml = await page.locator('[data-bm-print-frame]').evaluate(e => e.contentDocument.documentElement.outerHTML);
    const printPage = await context.newPage();
    await printPage.setContent(longHtml);
    await printPage.emulateMedia({ media: 'print' });
    const editableDiv = printPage.locator('td div[contenteditable]').last();
    assert.equal(await editableDiv.evaluate(e => getComputedStyle(e).borderTopStyle), 'none');
    const pdf = await printPage.pdf({ preferCSSPageSize: true });
    const texts = await page.evaluate(async bytes => {
      const lib = await import('/node_modules/pdfjs-dist/build/pdf.mjs');
      lib.GlobalWorkerOptions.workerSrc = '/node_modules/pdfjs-dist/build/pdf.worker.min.mjs';
      const document = await lib.getDocument({ data: new Uint8Array(bytes) }).promise;
      const texts = [];
      for (let n = 1; n <= document.numPages; n++) {
        texts.push((await (await document.getPage(n)).getTextContent()).items.map(item => item.str).join(' '));
      }
      await document.destroy();
      return texts;
    }, [...pdf]);
    assert.ok(texts.length >= 2);
    assert.ok(texts.every(text => text.includes('TRÍCH YẾU TÀI LIỆU')));
    assert.match(texts.at(-1), /Tài liệu kiểm tra số 40/);
    assert.ok(texts.every(text => !text.includes('Mở tệp ngoài')));
    await printPage.close();
    await page.locator('[data-bm-print-frame]').evaluate(e => e.remove());
    console.log('PASS real PDF: long table pagination, repeated headers, final row, no input borders or app content');
    await page.getByTitle('Đóng cửa sổ soạn thảo (Esc)').click();
    const external = '<html><body><p>Họ tên: <span contenteditable></span></p><select><option>A</option><option>B</option></select></body></html>';
    await page.locator('input[type=file]').setInputFiles({ name: 'test-form.html', mimeType: 'text/html', buffer: Buffer.from(external) });
    await paper.locator('[contenteditable]').fill('Phải được xóa');
    await paper.locator('select').selectOption('B');
    await page.getByTitle('Đóng cửa sổ soạn thảo (Esc)').click();
    await page.locator('input[type=file]').setInputFiles({ name: 'test-form.html', mimeType: 'text/html', buffer: Buffer.from(external) });
    assert.equal(await paper.locator('select').inputValue(), 'B');
    page.once('dialog', dialog => dialog.accept());
    await page.getByRole('button', { name: 'Xóa nháp', exact: true }).click();
    await page.waitForFunction(() => !document.querySelector('#bieumau-print-area')?.textContent.includes('Phải được xóa'));
    assert.equal(await paper.locator('select').inputValue(), 'A');
    console.log('PASS external: select draft restored, reset really clears live DOM');
    await page.getByTitle('Đóng cửa sổ soạn thảo (Esc)').click();
    await page.locator('input[type=file]').setInputFiles(path.resolve(__dirname, '../public/bieumau/pdf/B1.pdf'));
    await page.getByRole('button', { name: /Tạo bản đánh máy/ }).click();
    const frame = page.frameLocator('.pdf-editor-frame');
    const field = frame.locator('.pdf-form-field').first();
    await field.waitFor({ timeout: 60000 });
    await field.fill('Dòng một');
    await field.press('End');
    await field.press('Enter');
    await field.pressSequentially('Dòng hai');
    assert.match(await field.textContent(), /Dòng một\nDòng hai/);
    const geometry = await field.evaluate(e => ({ height: e.clientHeight, scroll: e.scrollHeight }));
    assert.ok(geometry.height >= geometry.scroll - 1);
    await page.getByRole('button', { name: 'In / Lưu PDF', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('[data-bm-print-frame]')?.contentWindow.__printed);
    assert.equal(await page.locator('[data-bm-print-frame]').evaluate(e => e.contentDocument.querySelectorAll('.pdf-form-page').length), 2);
    assert.equal(await page.locator('[data-bm-print-frame]').evaluate(e => e.contentDocument.querySelector('.pdf-form-field').textContent), 'Dòng một\nDòng hai');
    await page.locator('[data-bm-print-frame]').evaluate(e => e.remove());
    await page.getByRole('button', { name: 'Đóng bản đánh máy' }).click();
    await page.locator('input[type=file]').setInputFiles(path.resolve(__dirname, '../public/bieumau/pdf/B1.pdf'));
    await page.getByRole('button', { name: /Tạo bản đánh máy/ }).click();
    await field.waitFor({ timeout: 60000 });
    assert.equal(await field.textContent(), 'Dòng một\nDòng hai');
    assert.ok(page.url().endsWith('#/bieu-mau'));
    assert.deepEqual(errors, []);
    console.log('PASS PDF: Enter, preserved newlines, expanded height, correct print document, draft, stable route, no JS errors');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
